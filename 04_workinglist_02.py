#Working with list 04

players = ['charles', 'martina', 'michael', 'florence', 'eli']

#Display part of the lists
print('Players from 3-5:', players[2:5],'\n')

#Display part of the lists starting at beginning
print('The first 3 players:', players[:3],'\n')

#Display part of the lists from 2 to the end
print('The last 4 players:', players[2:],'\n')

#Display part of the lists starting from the end
print('The last 3 players:', players[-3:], '\n')

#Copy the lists
footballers = players[:]

print('Football players: ', footballers, '\n')